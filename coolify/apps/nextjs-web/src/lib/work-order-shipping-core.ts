/**
 * work-order-shipping-core.ts — 指示書からまだ出荷書へ載せられる数量。
 * 依存なし・isomorphic。
 *
 * **出荷書フォームと同じ数え方であることが、この関数の存在理由。**
 * フォーム（`DeliveryOrderForm` の `addSourceGroups`）は注文明細ごとに
 * `受注数 − 出荷済 ≤ 0` なら「出荷済み」としてスキップする。指示書側が
 * 別の数え方（完成数 − そのロットの出荷）をしていたため、
 * 指示書詳細は「次のステップ: 出荷書の作成」を出すのにフォームは
 * 「受注数量まで出荷済みです」と返して空の明細で開く、という食い違いが
 * 実際に起きた（デモデータで即再現した）。数え方を 1 か所に固定する。
 *
 * 出荷済みは **order_line_id で数える** — `delivery_order_items.lot_number` は
 * 任意列で、在庫保管の行やロット未指定の行では空になるため、ロットで数えると
 * 出荷済みを取りこぼす。
 *
 * ★ **「出荷済み」の数え方が 2 つあることは承知のうえ。**
 *   - 出荷書フォーム（`shippedQuantityForLine`）は **DISPATCH かつ SHIPPED** の
 *     行だけを数える（下書きの出荷書があってもまだ出せる、が過出荷ガードの立場）。
 *   - 未処理出荷書 SH03 と、この関数の呼び出し側は **下書きも含めて**数える
 *     （もう手配済みなら二重に出荷書を起こさせない）。
 *
 *   呼び出し側は後者で数えること。`全部 ≥ SHIPPED だけ` なので残数は必ず
 *   **少なめ**に出る = カードが出るなら フォームは必ず受け付ける、という
 *   向きになる。逆（カードは出るのにフォームが「出荷済みです」と断る）は
 *   利用者が空のフォームに放り出されるので、絶対に作ってはいけない。
 *   この向きを崩さない限り、2 つの数え方が共存していてよい。
 */

/** 出荷残の計算に必要な注文明細 1 件ぶん。 */
export interface ShippableLine {
  /** 受注数量（order_lines.quantity）。 */
  quantity: number;
  /** その明細について出荷書に載っている数量の合計（下書きを含む）。 */
  shippedQuantity: number;
}

/**
 * まだ出荷書へ載せられる数量の合計。
 *
 * 明細ごとに 0 で下限を切ってから足す — 受注数を超えて出荷済みの明細
 * （データ移行や手入力で実際にある）が、他の明細の残数を食い潰さないように。
 * 合計してから 0 で切ると、1 件の超過が別の明細の出荷を隠してしまう。
 */
export function shippableQuantity(lines: readonly ShippableLine[]): number {
  return lines.reduce(
    (sum, l) => sum + Math.max(0, l.quantity - l.shippedQuantity),
    0,
  );
}
