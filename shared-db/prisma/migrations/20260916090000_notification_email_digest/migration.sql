-- 通知メールを Teams 型のダイジェスト（見逃した未読だけを 1 通にまとめる）に
-- するための 1 列。
--
-- これまで通知は 1 件 = 1 通のメールで、アプリ内で既に読んだものにも同じだけ
-- メールが飛んでいた。「見逃したものだけ、まとめて」にするには、行ごとに
-- **メールに載せたかどうか**を持つ必要がある。null = まだ載せていない。
--
-- この 1 列で 2 つを兼ねる:
--   1. 同じ通知を二度メールしない（掃き出しの対象から外れる）
--   2. **そのユーザーへ最後に送った時刻** = MAX(email_sent_at)。送信間隔は
--      これで測れるので、user_notification_settings 側に列を足さない。
--
-- 即時送信（管理者が「この種別は待たせない」と決めたもの）でも同じ列に印を
-- 付ける — でないと即時で送った通知が次のダイジェストにもう一度載る。
--
-- 既存行は NULL で始まる。つまり「まだメールしていない」扱いになるが、
-- 未読でなければ掃き出しの対象にならないので、過去の既読分が今さら
-- メールされることはない。未読のまま放置されている分だけが、最初の
-- ダイジェストに 1 度だけ載る。

ALTER TABLE "app"."notifications"
  ADD COLUMN "email_sent_at" TIMESTAMPTZ(6);

-- ダイジェストの掃き出し（未読・未送信・猶予を過ぎたもの）用。
CREATE INDEX "notifications_is_read_email_sent_at_created_at_idx"
  ON "app"."notifications" ("is_read", "email_sent_at", "created_at");
