-- 管理ディスプレイ: 「どの機械の何枚目か」の手掛かりを足す。
--
-- Raspberry Pi 5 は HDMI が 2 口あり、1 台で 2 枚のテレビを回せる。画面ごとに
-- ブラウザのプロファイルを分けるので **1 枚 = display_devices の 1 行**で、
-- 表示内容も倍率も画面ごとに決まる（サーバー側のモデルは変えていない）。
--
-- ただし一覧では「2 枚まとめて消えた = 箱が落ちた / 1 枚だけ = ケーブルか
-- テレビ側」を見分けたい。そのために出どころを控える列。
--
-- ★ 値は Pi が URL に載せてくる自己申告なので**詐称できる**。表示とまとめ表示
--   にしか使わない — 認証にも権限にも使わない（端末シグネチャと同じ扱い）。
--
-- 列を足すだけなので前のバージョンのアプリは壊れない（読まないだけ）。
ALTER TABLE "app"."display_devices"
  ADD COLUMN "machine_id"   VARCHAR(64),
  ADD COLUMN "screen_index" INTEGER;
