-- 注文請書 明細の「単価の持ち主」を 1 列で持つ（§2 価格差異）。
--
-- これまで単価は行の自由入力で、価格表と違っても**入力ミスと意図の区別が
-- 付かなかった**（price-check.ts はどちらも「価格差異」として同じ警告を出す）。
-- そこで既定を「単価は価格表が持つ」に倒し、外すときだけ人が明示する。
--
--   false（既定） = 価格表どおり。保存時にサーバーが
--                   (顧客 × 製品 × 注文種別 × 数量) から解決した単価を書く。
--                   あとで価格表が変わって食い違えば、それは本当の差異。
--   true          = 人が「上書き」を入れて決めた単価。価格表と違うのは意図なので
--                   承認依頼を止めない（承認者の画面には出す）。
--
-- 既存行は false で入る — 取込・手入力された単価はそのまま残り、価格表と
-- 食い違う行は従来どおり「価格差異」として出る（意味が変わらない側へ倒す）。
-- 該当する価格表が無い行では意味を持たない（アプリ側で false に正規化する）。
ALTER TABLE app.order_lines
  ADD COLUMN IF NOT EXISTS price_overridden boolean NOT NULL DEFAULT false;
