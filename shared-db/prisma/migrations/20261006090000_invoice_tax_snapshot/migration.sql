-- 請求書に課税区分と税率のスナップショットを持たせる。
--
-- これまで請求書 PDF の税ラベル（10% / 8% / 非課税）は**顧客マスタの現在の
-- 課税区分**を描画時に読んでいた。締日処理が税額を計算したあとで顧客を
-- EXEMPT に変えると、過去の請求書が「10% 相当の税額」の隣に「非課税」と
-- 刷られる。金額は発行時点で凍結されているのだから、その根拠も一緒に凍結する。
--
-- 既存行は null のまま（当時の区分を後から復元する手立ては無い）。読み出し側は
-- null のとき従来どおり顧客の現在の区分へフォールバックする。
ALTER TABLE "app"."invoices"
  ADD COLUMN "tax_type" "app"."TAX_TYPE",
  ADD COLUMN "tax_rate" DECIMAL(5,4);
