-- quote-discount-notes — 見積書の値引き注記・明細備考（#973）の準備。
--
-- デモシードの製品はどれも製品マスタの備考（items.notes）を持たない。
-- 「製品マスタの備考を見積書の明細の備考へ**写さない**」ことを確かめるには、
-- 備考のある製品が要るので、超硬エンドミル（9001）に 1 つ持たせる。
-- この文言が見積書の入力欄・詳細・PDF のどこにも出てこないことを見る。
UPDATE app.items
   SET notes = 'SCN-MASTER-NOTE 製品マスタの社内備考（見積書には出さない）',
       updated_at = now()
 WHERE id = 9001;
